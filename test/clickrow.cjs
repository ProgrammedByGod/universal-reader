const { chromium } = require('playwright')
;(async () => {
  const [name, sel, shot] = process.argv.slice(2)
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1220, height: 820 } })
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 300)) })
  await p.goto('http://localhost:8765/index.html'); await p.evaluate(() => window.ready)
  console.log(await p.evaluate(n => openFile(n, {}), name))
  await p.waitForTimeout(1000)
  await p.locator(sel).first().click()
  await p.waitForTimeout(2000)
  console.log((await p.evaluate(() => document.querySelector('.ur-stage')?.innerText || '')).slice(-500)); await p.screenshot({ path: __dirname + '/shots/' + shot })
  console.log(errs.join('\n'))
  await b.close()
})()
