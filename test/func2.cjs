const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1220, height: 820 } })
  const errs = []; p.on('pageerror', e => errs.push(e.message))
  await p.goto('http://localhost:8765/index.html'); await p.evaluate(() => window.ready)
  await p.evaluate(() => openFile('test.xlsx')); await p.waitForTimeout(800)
  await p.evaluate(async () => { view.openSearch(); await view.runSearch('уникальноеслово') })
  console.log(await p.evaluate(() => view.searchInfo.textContent))
  await p.evaluate(() => view.searchResults.querySelector('.ur-search-hit').click()); await p.waitForTimeout(400)
  await p.screenshot({ path: 'shots/f-xlsx-search.png' })
  await p.evaluate(() => openFile('test.cbz')); await p.waitForTimeout(800)
  console.log('sidebar open on cbz:', await p.evaluate(() => view.sidebar.classList.contains('is-open')))
  console.log(errs)
  await b.close()
})()
