const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1000, height: 1100 } })
  const errs = []; p.on('pageerror', e => errs.push(e.message))
  await p.goto('http://localhost:8765/index.html'); await p.evaluate(() => window.ready)
  console.log('items', await p.evaluate(() => openSettings()))
  await p.evaluate(() => { document.getElementById('host').style.height = '1080px' })
  await p.click('.ur-set-group summary')
  await p.waitForTimeout(300)
  await p.screenshot({ path: 'shots/settings1.png' })
  // выключаем формат и проверяем, что расширение освободилось
  const before = await p.evaluate(() => app.viewRegistry.typeByExtension['fb2'])
  await p.evaluate(() => { const s = [...document.querySelectorAll('.setting-item')].find(x => x.querySelector('.setting-item-name')?.textContent === 'FictionBook 2'); s.querySelector('input').click() })
  await p.waitForTimeout(200)
  const after = await p.evaluate(() => [app.viewRegistry.typeByExtension['fb2'], app.viewRegistry.typeByExtension['fbz'], JSON.parse(localStorage.getItem('ur-data')).disabledExts])
  console.log('fb2 before', before, 'after', after)
  await p.fill('.ur-set-bar input', 'карт'); await p.waitForTimeout(300)
  await p.screenshot({ path: 'shots/settings2.png' })
  console.log('search hits', await p.evaluate(() => [...document.querySelectorAll('.ur-set-group')].map(g => g.querySelector('.ur-set-gname').textContent + ':' + g.querySelectorAll('.setting-item').length).join(', ')))
  await p.evaluate(() => { const s = [...document.querySelectorAll('.setting-item')].length })
  // включаем обратно
  await p.fill('.ur-set-bar input', 'fb2'); await p.waitForTimeout(200)
  await p.evaluate(() => document.querySelector('.ur-set-list .setting-item input').click())
  console.log('fb2 again', await p.evaluate(() => app.viewRegistry.typeByExtension['fb2']), 'summary:', await p.evaluate(() => document.querySelector('.ur-set-summary').textContent))
  console.log('errors', errs)
  await p.evaluate(() => localStorage.removeItem('ur-data'))
  await b.close()
})()
